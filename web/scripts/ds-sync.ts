// Übernimmt aus dem Intersys-Design-System-Export (tokens.css + components/bundle.css bzw. das daraus
// generierte intersys.css) nur Tokens, Basis-Styles und die Komponenten, die dieses Tool verwendet.
// Aufruf: npm run ds:sync -w web -- <pfad/zu/intersys.css> [weitere.css …]
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const OUTPUT = fileURLToPath(new URL('../src/design/intersys.css', import.meta.url));

// Komponenten laut docs/agents/design.md. Neue Komponenten hier ergänzen, dann neu synchronisieren.
const ALLOWED_CLASSES = new Set([
  'button',
  'button--outline',
  'button--white',
  'card',
  'check-field',
  'container',
  'container--narrow',
  'empty-state',
  'empty-state__icon',
  'eyebrow',
  'filter-option',
  'filters',
  'form',
  'form-field',
  'form-field__error',
  'form-field__hint',
  'meta',
  'notice',
  'notice--error',
  'notice--success',
  'skip-link',
  'table-scroll',
  'tag',
  'tag-list',
  'visually-hidden',
]);

// Ab hier folgen Website-Anpassungen; klassenlose Regeln daraus (z. B. scroll-margin für die fixe Kopfzeile) gelten nicht fürs Tool.
const SITE_SECTION_MARKER = 'Abgleich mit der Website';
const COMPONENTS_MARKER = 'Intersys Design System: components/';

type Section = 'tokens' | 'components' | 'site';

type Node =
  | { kind: 'comment'; text: string }
  | { kind: 'rule'; prelude: string; text: string }
  | { kind: 'block'; prelude: string; children: Node[] };

function matchingBrace(css: string, open: number): number {
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css.startsWith('/*', i)) {
      i = css.indexOf('*/', i + 2) + 1;
    } else if (css[i] === '"' || css[i] === "'") {
      i = css.indexOf(css[i]!, i + 1);
    } else if (css[i] === '{') {
      depth++;
    } else if (css[i] === '}' && --depth === 0) {
      return i;
    }
  }
  throw new Error(`Nicht geschlossene Klammer ab Position ${open}`);
}

function parse(css: string): Node[] {
  const nodes: Node[] = [];
  let i = 0;
  while (i < css.length) {
    if (/\s/.test(css[i]!)) {
      i++;
    } else if (css.startsWith('/*', i)) {
      const end = css.indexOf('*/', i + 2) + 2;
      nodes.push({ kind: 'comment', text: css.slice(i, end) });
      i = end;
    } else {
      const open = css.indexOf('{', i);
      if (open === -1) break;
      const prelude = css.slice(i, open).trim();
      const close = matchingBrace(css, open);
      if (prelude.startsWith('@')) nodes.push({ kind: 'block', prelude, children: parse(css.slice(open + 1, close)) });
      else nodes.push({ kind: 'rule', prelude, text: css.slice(i, close + 1) });
      i = close + 1;
    }
  }
  return nodes;
}

const classesOf = (selector: string) =>
  [...selector.replace(/"[^"]*"|'[^']*'/g, '').matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)].map((match) => match[1]!);

function keepRule(prelude: string, text: string, section: Section): boolean {
  const classes = classesOf(prelude);
  if (classes.length > 0) return classes.every((name) => ALLOWED_CLASSES.has(name));
  if (section === 'tokens') return true;
  // Variablen ausserhalb der Tokens gehören zu Website-Komponenten (z. B. --site-header-height).
  return section === 'components' && !/\{\s*--/.test(text);
}

function select(nodes: Node[], state: { section: Section }, indent = ''): string[] {
  const out: string[] = [];
  let comments: string[] = [];
  for (const node of nodes) {
    if (node.kind === 'comment') {
      if (node.text.includes(SITE_SECTION_MARKER)) state.section = 'site';
      else if (node.text.includes(COMPONENTS_MARKER)) state.section = 'components';
      if (!node.text.startsWith('/* Generated by') && state.section !== 'site') comments.push(indent + node.text);
      continue;
    }
    let kept: string | null = null;
    if (node.kind === 'rule' && keepRule(node.prelude, node.text, state.section)) {
      kept = indent + node.text;
    } else if (node.kind === 'block') {
      const inner = select(node.children, state, `${indent}  `);
      if (inner.length > 0) kept = `${indent}${node.prelude} {\n${inner.join('\n')}\n${indent}}`;
    }
    if (kept) out.push(...comments, kept);
    comments = [];
  }
  return out;
}

const inputs = process.argv.slice(2);
if (inputs.length === 0) {
  console.error('Aufruf: npm run ds:sync -w web -- <pfad/zu/intersys.css>');
  process.exit(1);
}

const cwd = process.env.INIT_CWD ?? process.cwd();
const sources = inputs.map((file) => path.resolve(cwd, file));
const css = sources.map((file) => readFileSync(file, 'utf8')).join('\n');
const origin = /export [\w-]+/.exec(css)?.[0] ?? 'unbekannter Export';

const header = `/* Generiert mit npm run ds:sync aus dem Intersys Design System (${origin}). Nicht von Hand ändern:
   Auswahl in web/scripts/ds-sync.ts anpassen, eigene Ergänzungen gehören in additions.css. */`;

writeFileSync(OUTPUT, `${header}\n${select(parse(css), { section: 'tokens' }).join('\n')}\n`);
console.info(`${path.relative(cwd, OUTPUT)} aus ${sources.map((file) => path.relative(cwd, file)).join(', ')} erzeugt`);
